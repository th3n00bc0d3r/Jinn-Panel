/** Zone file text the way DnsService::render() writes it. */
function sample_dns_zone_file(array $zone, array $ns, array $records): string
{
    $name = (string) $zone['zone_name'];
    $lines = [
        '; Generated by JinnPanel from its database. Edit records in WHM > DNS Zones;',
        '; direct edits to this file are overwritten on the next publish.',
        "\$ORIGIN {$name}.",
        '$TTL 3600',
        sprintf('@ IN SOA ns1.example.com. hostmaster.%s. ( %d 3600 900 604800 3600 )', $name, (int) $zone['serial']),
    ];
    foreach (array_merge($ns, $records) as $r) {
        $rdata = match ($r['type']) {
            'MX', 'SRV' => (int) $r['priority'] . ' ' . $r['content'],
            'TXT' => implode(' ', array_map(fn(string $c) => '"' . addcslashes($c, '"\\') . '"', str_split((string) $r['content'], 255))),
            default => (string) $r['content'],
        };
        $lines[] = sprintf('%-24s %6d IN %-5s %s', $r['name'], (int) $r['ttl'], $r['type'], $rdata);
    }
    return implode("\n", $lines) . "\n";
}

