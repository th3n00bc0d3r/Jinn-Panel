<?php
require_once __DIR__ . '/../_sample.php';

$wordpress = "# BEGIN WordPress\n<IfModule mod_rewrite.c>\nRewriteEngine On\nRewriteBase /\nRewriteRule ^index\\.php$ - [L]\n"
    . "RewriteCond %{REQUEST_FILENAME} !-f\nRewriteCond %{REQUEST_FILENAME} !-d\nRewriteRule . /index.php [L]\n</IfModule>\n# END WordPress\n\n"
    . "Redirect 301 /old-shop https://shop.acme.test/\nErrorDocument 404 /404.html\nHeader set X-Frame-Options \"SAMEORIGIN\"\nExpiresActive On\n";
$uploads = "<Files *.php>\nRequire all denied\n</Files>\n";
$files = ['' => $wordpress, 'wp-content/uploads' => $uploads];

// What HtaccessTranslator::translate() makes of $files (copied, so the fixture never depends on it).
$head = "# Generated by JinnPanel from .htaccess - see the review notes in cPanel > Domains > Routes.\n";
$route = <<<'CADDY'
@d3 {
	path /wp-content/uploads /wp-content/uploads/*
	vars_regexp {http.request.uri.path.file} ^[^/]*\.php$
}
error @d3 403
@r1 path_regexp r1 ^/index\.php$
handle @r1 {
}
@r2 {
	path_regexp r2 ^/.
	not file {path} {path}/
}
handle @r2 {
	rewrite * /index.php
}
@a4 vars_regexp a4 {http.request.orig_uri.path} ^/old\-shop(/.*)?$
redir @a4 https://shop.acme.test/{re.a4.1}{?query} 301
@a5 path_regexp a5 ^/old\-shop(/.*)?$
redir @a5 https://shop.acme.test/{re.a5.1}{?query} 301
@t6 {
	path /wp-content/uploads /wp-content/uploads/*
	vars_regexp {http.request.uri.path.file} ^[^/]*\.php$
}
error @t6 403
@nophp {
	path *.php
	not file {path}
}
error @nophp 404
php_server {
	try_files {path} {path}/index.php
}

CADDY;
$site = <<<'CADDY'
header >X-Frame-Options SAMEORIGIN
handle_errors 404 {
	rewrite * /404.html
	file_server {
		status 404
	}
}

CADDY;
$note = fn(int $line, string $directive, string $status, string $message, string $file = '') => compact('file', 'line', 'directive', 'status', 'message');
$notes = [
    $note(3, 'RewriteEngine On', 'translated', 'Rewrite engine on.'),
    $note(8, 'RewriteRule . /index.php [L]', 'translated', 'Internal rewrite.'),
    $note(12, 'Redirect 301 /old-shop https://shop.acme.test/', 'translated', 'Redirect (301).'),
    $note(13, 'ErrorDocument 404 /404.html', 'translated', 'Custom 404 page (site rules).'),
    $note(14, 'Header set X-Frame-Options "SAMEORIGIN"', 'translated', 'Site-wide header (site rules).'),
    $note(15, 'ExpiresActive On', 'ignored', 'mod_expires is not translated; set Cache-Control with Header instead.'),
    $note(2, 'Require all denied', 'translated', 'Access denied (403).', 'wp-content/uploads'),
];
$generated = ['route' => $head . $route, 'site' => $head . $site, 'notes' => $notes, 'needs_review' => false];

// Password protection can't be translated: the sync keeps the rules in use and asks for a review.
$reviewFiles = ['' => $wordpress . "AuthType Basic\nAuthName \"Staff\"\nAuthUserFile /home/acme/.htpasswd\nRequire valid-user\n", 'wp-content/uploads' => $uploads];
$auth = 'Password protection is not translated; the folder answers 403 until it is set up again.';
$reviewGenerated = [
    'route' => $head . "error * 403\n" . $route,
    'site' => $head . $site,
    'notes' => array_merge($notes, [
        $note(16, 'AuthType Basic', 'unsupported', $auth),
        $note(17, 'AuthName "Staff"', 'unsupported', $auth),
        $note(18, 'AuthUserFile /home/acme/.htpasswd', 'unsupported', $auth),
        $note(19, 'Require valid-user', 'unsupported', 'This Require rule is not translated; the folder answers 403 until reviewed.'),
    ]),
    'needs_review' => true,
];

$ago = fn(int $s) => date('c', time() - $s);
$d = array_replace(sample_domains()[0], [
    'routes_sync' => 1,
    'routes_review' => 0,
    'routes_sync_note' => 'Applied the .htaccess change.',
    'routes_synced_at' => date('Y-m-d H:i:s', time() - 900),
]);
$o = ['files' => $files, 'generated' => $generated, 'current' => ['route' => $generated['route'], 'site' => $generated['site']]];

return [
    'layout' => 'cpanel',
    'role' => 'user',
    'path' => '/cpanel/domains/1/routes',
    'data' => [
        'title' => 'Routes · acme.test',
        'd' => $d,
        'o' => $o,
        'last' => '[' . $ago(900) . '] OK',
        'pending' => false,
    ],
    'variants' => [
        'limited-package' => ['features' => ['file_manager' => false, 'cron' => false, 'backups' => false, 'dns_editor' => false, 'php_versions' => false, 'aliases' => false, 'routes' => false, 'object_cache' => false, 'database_access' => false, 'ssh_keys' => false]],
        'applying' => ['pending' => true],
        'needs-review' => [
            'd' => array_replace($d, ['routes_review' => 1, 'routes_sync_note' => '.htaccess changed, but some of it can\'t be translated exactly - the rules in use were kept. Review the translation below and use it if it is right.']),
            'o' => ['files' => $reviewFiles, 'generated' => $reviewGenerated, 'current' => $o['current']],
        ],
        // Rules edited by hand (following .htaccess is off), and the last save was rejected.
        'failed' => [
            'd' => array_replace($d, ['routes_sync' => 0, 'routes_sync_note' => null, 'routes_synced_at' => null]),
            'o' => ['files' => $files, 'generated' => $generated, 'current' => ['route' => "@legacy path /catalog/*\nredir @legacy /shop{path} 301\n" . $route, 'site' => null]],
            'last' => '[' . $ago(120) . '] FAILED: Caddy rejected the rules: Caddyfile:4 - Error during parsing: unrecognized directive: redirect',
        ],
        // A new site: no .htaccess, no rules, not checked yet.
        'default' => [
            'd' => array_replace($d, ['routes_sync' => null, 'routes_sync_note' => null, 'routes_synced_at' => null]),
            'o' => ['files' => [], 'generated' => ['route' => '', 'site' => '', 'notes' => [], 'needs_review' => false], 'current' => ['route' => null, 'site' => null]],
            'last' => null,
        ],
    ],
];
